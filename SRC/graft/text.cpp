// Память под возвращаемые строки: `owned string` из натива и строковые out-аргументы.
//
// ── ЧТО ТРЕБУЕТ ДВИЖОК (выяснено, а не предположено) ─────────────────────────
//
// 1. Эксперимент (кейсы Arena_* в сьюте): натив затирает всю выданную память, скрипт
//    смотрит, уцелел ли текст. Результат — движок НЕ копирует возвращённый const char*
//    в момент возврата. Он держит наш указатель на стеке выражения и копирует только
//    когда значение потребляется: присваивание, вставка в контейнер, передача дальше.
//
// 2. Реверс (re/scripts/owned5.py): путь потребления строковой переменной проверяет
//    ТОЛЬКО семейство тега (0x50000000) и флаг no-write (0x40), после чего зовёт
//    присваивание строки из char* — то есть копию. Бит `owned` (0x800) там не участвует:
//    компилятор ставит его на переменную, и на этом всё. Движок нашу память не
//    освобождает и своей взамен не даёт.
//
// Отсюда контракт: возвращённый указатель обязан жить, пока движок его не скопирует —
// то есть до конца ОПЕРАТОРА скрипта, а не до конца вызова натива. Границу оператора из
// C++ не видно: внутри одного `m.Insert(A(), B())` наших вызовов два.
//
// ── УСТРОЙСТВО И ЕГО ГРАНИЦА ─────────────────────────────────────────────────
//
// Раз освободить по событию нельзя, держим ОКНО последних строк. Правило одно и то же
// для строк любой длины:
//
//    строка живёт, пока после неё не выдадут kRing байт новых.
//
// Кольцо фиксированного размера, аллокация одна на поток и та ленивая. Строки длиннее
// кольца в него не влезают (обнулили бы его целиком) — им отдельные блоки, но живут они
// по ТОМУ ЖЕ правилу, а не «последние N штук»: иначе пять подряд огромных строк в одном
// операторе освободили бы первую прямо под движком, а это уже обращение к освобождённой
// памяти, а не просто неверный текст.
//
// ЧТО БУДЕТ, ЕСЛИ ОКНО ВСЁ-ТАКИ ПЕРЕПОЛНИТЬ. Отказ ограниченный, и он проверен кейсом
// Arena_OverrunGivesWrongText: движок скопирует НЕ ТОТ текст. Ни выхода за пределы
// блока, ни обращения к освобождённой памяти не происходит — блок целиком наш, при
// создании занулён, и каждая записанная строка оставляет в нём свой терминатор, поэтому
// чтение из любой точки блока упирается в ноль, не покидая его.
//
// Сколько строк помещается: 16 КБ при типичной строке в 50 байт — порядка трёхсот. Чтобы
// окно переполнилось, ОДИН оператор скрипта должен вызвать три сотни нативов,
// возвращающих строку. Это и есть граница применимости, и она записана здесь явно.
//
// Размер выбран по запасу, а не по скорости: замер на кольце в 1 КБ дал те же цифры
// (textLong 4.39 против 4.39, textArena 3.43 против 3.34) — 16 КБ и так помещаются в L1.
//
// ── ПОЧЕМУ НЕ АЛЛОКАТОР САМОГО ДВИЖКА ────────────────────────────────────────
//
// Он найден и был реализован целиком: якорь по литералу `enf_scriptcontext.cpp` плюс
// номер строки 2499 и признак `lea rdx,[rcx+2E0h]` (база фрилистов), проба на живом
// контексте, выдача блоков через него. Заманчиво: блок движковый, ёмкость в dword по
// адресу-8 валидна, владение переходит движку, своей памяти не нужно ни байта.
//
// Отвергнуто замером. Строку, которую скрипт НЕ ПОТРЕБИЛ, движок не освобождает: тест
// Arena_DiscardedStringsDoNotLeak на 200000 отброшенных строк дал +14.7 МБ приватной
// памяти против +0 у кольца. То есть течёт каждая, а на сервере, живущем неделями, это
// смертельно. Плюс он на 25-33% медленнее (text 3.14 против 2.36, textLong 5.81 против
// 4.68, textArena 4.61 против 3.56 — замер в одной сессии, туда и обратно).
//
// Вывод: кольцо не хуже «правильного» владения, а лучше — потому что переиспользование
// не требует, чтобы кто-то освобождал. Разбор аллокатора остался в re/scripts/salloc*.py.
namespace graft::detail {
namespace {

constexpr std::size_t kRing = 16 * 1024;

struct big {
    std::unique_ptr<char[]> mem;
    std::size_t served_at = 0;  // сколько всего было выдано на момент создания
};

struct arena {
    std::unique_ptr<char[]> ring;  // ленивая: поток, не возвращающий строк, не платит
    std::size_t at = 0;            // куда писать следующую
    std::size_t depth = 0;         // вложенность вызовов (считает call_scope)
    std::size_t served = 0;        // всего выдано за жизнь потока, монотонно
    std::size_t chain = 0;         // выдано с прошлого входа на глубину 0
    std::size_t peak_chain = 0;    // максимум chain — см. peak_demand()
    std::vector<big> oversized;
};

arena& current() {
    thread_local arena a;
    return a;
}

char* take(arena& a, std::size_t n) {
    const std::size_t need = n + 1;  // вместе с терминатором
    a.served += need;
    a.chain += need;
    a.peak_chain = std::max(a.peak_chain, a.chain);

    if (need > kRing) {
        a.oversized.push_back({std::make_unique<char[]>(need), a.served});
        return a.oversized.back().mem.get();
    }
    if (!a.ring) {
        // make_unique зануляет: в блоке всегда есть терминатор впереди, поэтому чтение
        // даже из «чужой» точки блока не уходит за его пределы.
        a.ring = std::make_unique<char[]>(kRing);
    }
    if (a.at + need > kRing) {
        a.at = 0;  // кольцо: затираем самое старое
    }
    char* at = a.ring.get() + a.at;
    a.at += need;
    return at;
}

}  // namespace

const char* stash(std::string_view text) {
    char* at = take(current(), text.size());
    std::memcpy(at, text.data(), text.size());
    at[text.size()] = '\0';
    return at;
}

char* reserve_text(std::size_t bytes) {
    return take(current(), bytes);
}

void enter_call() {
    arena& a = current();
    if (a.depth++ != 0) {
        return;  // вложенный вызов — та же цепочка, окно не двигаем
    }
    a.chain = 0;
    // Блоки сверх кольца отпускаем по тому же правилу, что и само кольцо: когда после
    // строки выдали kRing байт новых. По счёту («держим последние четыре») было бы
    // дешевле, но неверно — см. комментарий вверху файла.
    if (!a.oversized.empty()) {
        const std::size_t cutoff = a.served > kRing ? a.served - kRing : 0;
        std::erase_if(a.oversized, [cutoff](const big& b) { return b.served_at < cutoff; });
    }
}

void leave_call() {
    arena& a = current();
    if (a.depth > 0) {
        --a.depth;
    }
}

// Вызов оборвался падением. При раскрутке SEH деструкторы не бегут, поэтому call_scope
// сам не закроется, и глубина уехала бы навсегда: следующий вызов считался бы вложенным,
// окно арены перестало бы двигаться, и кольцо переполнилось бы тихо. Сбрасываем её.
void abandon_calls() {
    current().depth = 0;
}

// Максимум байт, выданных за ОДНУ ЦЕПОЧКУ вызовов (от входа на глубину 0 до выхода).
// ВНИМАНИЕ: это НЕ расход на оператор скрипта. В `m.Insert(A(), B())` цепочек две, и
// счётчик видит каждую по отдельности — расход на оператор из C++ измерить нечем, ровно
// по той же причине, по которой нельзя освободить память по концу оператора. Число
// годится как порядок величины одной строки, а не как доказательство запаса.
std::size_t peak_demand() {
    return current().peak_chain;
}

std::size_t ring_size() {
    return kRing;
}

// ДИАГНОСТИКА, не рабочий путь: затирает всё выданное. Ею измерено требование движка
// ко времени жизни — см. кейсы Arena_* в сьюте.
std::size_t poison_arena() {
    arena& a = current();
    if (a.ring) {
        std::memset(a.ring.get(), 'X', kRing);
    }
    for (big& b : a.oversized) {
        b.mem[0] = 'X';
    }
    return a.at;
}

// ДИАГНОСТИКА: прокрутить кольцо, выдав не меньше bytes байт. Ею проверяется, что
// переполнение окна даёт неверный текст, а не падение.
std::size_t churn_arena(std::size_t bytes) {
    arena& a = current();
    const std::size_t was = a.peak_chain;  // стресс-инструмент не выдаёт себя за спрос
    const std::string filler(63, '#');
    std::size_t done = 0;
    while (done < bytes) {
        stash(filler);
        done += filler.size() + 1;
    }
    a.peak_chain = was;
    return done;
}

}  // namespace graft::detail

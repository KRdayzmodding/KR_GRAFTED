#pragma once
#include <cstddef>

// Заморозка потоков процесса на время патча чужого кода.
//
// ЗАЧЕМ ОНА ВООБЩЕ НУЖНА. Переписать пролог функции — не атомарная операция: переход
// занимает пять байт и более, а поток может стоять ВНУТРИ этих байт в момент записи.
// Возобновившись, он продолжит с середины уже другой инструкции. Лечится ровно одним
// способом: остановить потоки, записать патч, переставить rip тем, кто попал внутрь,
// и отпустить.
//
// ПОЧЕМУ ЭТО НАШ КОД, А НЕ ЧУЖОЙ. safetyhook решает ту же задачу иначе: снимает со
// страницы права и ловит обращения своим векторным обработчиком, отвечая ему
// «продолжай». Способ дешевле и переносится на Linux, но для graft он неприемлем по
// двум причинам, и обе проверяются кейсами Hook.* :
//
//   1. Обработчик регистрируется с First = 1, то есть ВЫШЕ кадрового. Библиотека
//      обещает забрать падение натива себе (guard.hpp) — с чужим обработчиком наверху
//      это обещание держится на том, что он согласится пропустить сбой дальше.
//   2. Список отравленных страниц не чистится никогда. Каждая пара врезка+снятие
//      добавляет две записи навсегда: и линейный поиск по ним на КАЖДОМ сбое в
//      процессе, и растущий шанс, что настоящий сбой получит «продолжай» — вечный
//      цикл вместо честного падения с минидампом.
//
// Заморозка обоих недостатков лишена: после неё в процессе не остаётся ничего.
//
// ЧЕМ ПЛАТИМ. Остановка потоков стоит десятки миллисекунд (снимок toolhelp снимает
// потоки ВСЕЙ системы и потом фильтрует по своему процессу), поэтому врезки ставят на
// старте, а не по ходу игры. Ради этого же существует пачка: область вложенная, и на
// всю пачку заморозка одна.
namespace graft::freeze {

// Пока жив хоть один объект — потоки процесса стоят. Вложенный ничего не морозит
// повторно: считается глубина. Область держит общий замок, поэтому два потока не
// смогут патчить одновременно.
struct scope {
    scope();
    ~scope();
    scope(const scope&) = delete;
    scope& operator=(const scope&) = delete;

    // Переставить rip замороженным потокам, стоящим внутри [from, from + len), на
    // соответствующий байт в to. Звать ПОСЛЕ записи патча и ДО выхода из области:
    // снаружи потоки уже бегут, и правка контекста опоздает.
    void relocate(void* from, void* to, std::size_t len) const;
};

}  // namespace graft::freeze

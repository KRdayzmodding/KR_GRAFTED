// Роль процесса. Плагины сервер и клиент берут одинаково — из `-mod=`, `-serverMod=` и
// <игра>/grafted. Различаются они двумя вещами: клиент следит за BattlEye (battleye.hpp) и,
// не получив `-profiles=`, пишет журнал в %LOCALAPPDATA%\DayZ.
enum class role : std::uint8_t {
    server,
    client
};

// Есть ли в командной строке ОТДЕЛЬНЫЙ флаг. По нему role_of() решает, серверный ли это
// процесс.
//
// Именно ОТДЕЛЬНЫЙ: «-server» встречается и внутри путей, и внутри имён модов
// (@my-server-mod), а нам нужен аргумент, а не подстрока. Inline и в заголовке, потому
// что это единственная часть установки, которую можно проверить без игры, — и она
// проверяется (кейсы Serving.* в runtime_test), а engine.cpp живёт только в самой DLL.
inline bool has_flag(const std::wstring& cmd, const wchar_t* flag) {
    const std::wstring want = flag;
    for (std::size_t at = cmd.find(want); at != std::wstring::npos; at = cmd.find(want, at + 1)) {
        const bool left = at == 0 || cmd[at - 1] == L' ' || cmd[at - 1] == L'"';
        const std::size_t end = at + want.size();
        const bool right = end == cmd.size() || cmd[end] == L' ' || cmd[end] == L'"';
        if (left && right) {
            return true;
        }
    }
    return false;
}

// Роль по тому, как игру запустили, — ровно так же, как отличает сам движок. Отдельному
// серверному exe хватает имени; диаг-сборка одна на всё и различается флагом -server.
//
// Смотрим на имя ФАЙЛА, а не на весь путь: клиент, лежащий в каталоге со словом Server в
// названии, сервером не становится. Раньше проверялся путь целиком, и такая установка
// принимала клиент за сервер. Inline по той же причине, что и has_flag.
inline role role_of(std::wstring_view exe_path, const std::wstring& cmd) {
    const std::size_t slash = exe_path.find_last_of(L"\\/");
    std::wstring      name{slash == std::wstring_view::npos ? exe_path : exe_path.substr(slash + 1)};
    for (wchar_t& c : name) {
        c = (c >= L'A' && c <= L'Z') ? static_cast<wchar_t>(c + (L'a' - L'A')) : c;
    }
    if (name.find(L"server") != std::wstring::npos) {
        return role::server;
    }
    return has_flag(cmd, L"-server") ? role::server : role::client;
}


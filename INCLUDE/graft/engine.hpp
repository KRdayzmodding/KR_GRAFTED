#pragma once
#include <string>
#include <string_view>

// Врезка в живой процесс игры: найти точки регистрации нативов и подсунуть движку
// всё, что накопили блоки GRAFT_BINDINGS. Зашитых адресов нет, см. scan.hpp.
namespace graft {

// Вызывать один раз при загрузке DLL (из отдельного потока, не из DllMain).
// Если в процессе нет скриптового движка (не сервер/не диаг) — тихо ничего не делает.
void install();

// Серверный ли это процесс. Решается ДО всего остального: в клиенте библиотека не делает
// вообще ничего — ни потока, ни скана, ни хуков, ни загрузки плагинов.
bool serving();

// Есть ли в командной строке ОТДЕЛЬНЫЙ флаг. По нему install() решает, серверный ли это
// процесс: в клиент библиотека не вмешивается вовсе.
//
// Именно ОТДЕЛЬНЫЙ: «-server» встречается и внутри путей, и внутри имён модов
// (@my-server-mod), а нам нужен аргумент, а не подстрока. Inline и в заголовке, потому
// что это единственная часть установки, которую можно проверить без игры, — и она
// проверяется (кейсы Serving.* в runtime_test), а engine.cpp живёт только в самой DLL.
inline bool has_flag(const std::wstring& cmd, const wchar_t* flag) {
    const std::wstring want = flag;
    for (std::size_t at = cmd.find(want); at != std::wstring::npos; at = cmd.find(want, at + 1)) {
        const bool left = at == 0 || cmd[at - 1] == L' ' || cmd[at - 1] == L'"';
        const std::size_t end = at + want.size();
        const bool right = end == cmd.size() || cmd[end] == L' ' || cmd[end] == L'"';
        if (left && right) {
            return true;
        }
    }
    return false;
}

// Ещё раз попытаться зарегистрировать методы классов, которых не было в момент врезки
// (игровые классы, инстанциации шаблонов мода). Библиотека делает это сама на регистрации
// каждого следующего модуля; звать руками нужно только если инстанциация появляется в
// самом последнем модуле. Ненайденное после этого попадёт в журнал.
void bind_pending();

// Журнал рядом с exe (<каталог exe>/graft.log) — единственный канал наружу процесса.
// Пока путь не задан, log() молчит.
void set_log_path(std::string_view path);
// string_view, а не const std::string&: половина вызовов — литералы, и на каждом из них
// приходилось строить std::string ради одной записи в журнал.
void log(std::string_view line);

// ── Точка входа для кода на C++ ──────────────────────────────────────────────
// Своего потока у библиотеки нет и не будет: строковый аллокатор движка без блокировок,
// кадр вызова у скриптового потока свой, и всё, что мы делаем, законно только там.
// Поэтому C++ просыпается там же, где живёт скрипт, — на тике мода:
//
//   GRAFT_ON_TICK(dt) { ... обычный C++, можно звать движок ... }
//
// со стороны мода это одна строка в OnUpdate (её печатает `graft protogen`):
//   modded class MissionServer { void OnUpdate(float t) { super.OnUpdate(t); GraftTick(t); } }
//
// Обработчиков может быть сколько угодно; зовутся в порядке регистрации.
void on_tick(void (*fn)(float));

namespace detail {
// Подписка из статического инициализатора: работает и до того, как хост представился.
struct tick_binder {
    explicit tick_binder(void (*fn)(float));
};
}  // namespace detail

}  // namespace graft

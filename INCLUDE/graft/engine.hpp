// ── Врезка в чужой код ───────────────────────────────────────────────────────
// Найти движковую функцию библиотека уже умеет (scan.hpp); перехватить её — вторая
// половина того же дела, и делать её плагину самому нечем.
//
// ПОЧЕМУ ЭТО СЕРВИС ХОСТА, А НЕ БИБЛИОТЕКА В ПЛАГИНЕ. Две механики врезки в одном
// процессе друг о друге не знают: у каждой свой пул трамплинов и свой список целей.
// Пока цели разные — сходит с рук; как только двум плагинам понадобится одна функция,
// второй перепишет пролог, в котором уже стоит чужой переход, и трамплин первого
// поведёт в середину инструкции. Одна на процесс это просто не даёт сделать: повторная
// врезка в ту же цель — честный отказ.
//
// Список целей ведёт САМ ХОСТ (SRC/graft/hook.cpp), а не библиотека под ним: у
// safetyhook такого списка нет вовсе, он принимает вторую врезку в ту же функцию и
// строит цепочку. Тем более незачем заводить свою копию плагину — отказ живёт в хосте.
//
// original получает адрес ТРАМПЛИНА: оригинал зовут через него, а не по target — по
// target теперь лежит переход к детуру. Адрес записан ДО того, как детур станет
// доступен чужому потоку: иначе первый же вызов ушёл бы в ноль.
//
// Ловушка, стоившая трёх падений сервера, записана в scan.hpp у frame_entry: хук на
// ФУНКЦИЮ, которую зовут из сотен мест с разными аргументами, ломает чужие вызовы —
// детур на C++ считает регистры xmm своими. Если место вызова известно, перенаправлять
// надо его (так сделан кадр, SRC/graft/frame.cpp), а не функцию. У safetyhook для
// второго случая есть MidHook — он сохраняет и xmm, и флаги, — но врезка в место вызова
// всё равно лучше: она точна (только тот вызов, а не все) и не стоит ничего, а MidHook
// сохраняет шестнадцать регистров xmm на КАЖДОМ вызове из всех сотен мест. Заводить его
// стоит, когда понадобится цель, у которой места вызова неизвестны.
bool hook(void* target, void* detour, void** original);
bool unhook(void* target);

// Те же, но без трёх приведений на месте вызова. Типы цели, детура и оригинала обязаны
// СОВПАСТЬ — иначе кадр вызова разъедется молча, а компилятор об этом не скажет:
//   graft::hook(&Engine_Foo, &my_foo, &g_orig);
template <class F>
    requires std::is_pointer_v<F>
bool hook(F target, F detour, F* original) {
    return hook(reinterpret_cast<void*>(target), reinterpret_cast<void*>(detour), reinterpret_cast<void**>(original));
}

template <class F>
    requires std::is_pointer_v<F>
bool unhook(F target) {
    return unhook(reinterpret_cast<void*>(target));
}

// ── Врезка пачкой ────────────────────────────────────────────────────────────
// Пачка нужна ровно за одним: она встаёт ЦЕЛИКОМ либо не встаёт вовсе. Половина врезок —
// это состояние, в котором мод уже сломан, но ещё считает себя живым, и разбирать его по
// журналу потом некому. Создание разбирает пролог и строит трамплин, ничего не трогая;
// патч идёт вторым проходом, и если хоть одна заявка не создалась, до патча дело не
// доходит вовсе.
//
// Дешевле поштучной установки она НЕ становится: сама врезка стоит сотые доли
// миллисекунды (замер печатает кейс Hook.InstallCostIsMeasured).
//
// КОГДА ВРЕЗКА БЕЗОПАСНА — контракт, а не пожелание: её ставят из точки входа плагина, до
// того как движок создаст свои потоки. Почему это не пожелание и чем кончается нарушение,
// записано в SRC/graft/hook.cpp.
using hook_request = graft_hook_request;

bool hook_all(std::span<const hook_request> all);

inline bool hook_all(std::initializer_list<hook_request> all) {
    return hook_all(std::span<const hook_request>{all.begin(), all.size()});
}

// Заявка со сверкой типов — чтобы на месте вызова не было трёх приведений к void*, за
// которыми компилятор уже ничего не проверяет:
//   graft::hook_all({graft::hooked(&Engine_Foo, &my_foo, &g_foo),
//                    graft::hooked(&Engine_Bar, &my_bar, &g_bar)});
template <class F>
    requires std::is_pointer_v<F>
hook_request hooked(F target, F detour, F* original) {
    return {reinterpret_cast<void*>(target), reinterpret_cast<void*>(detour), reinterpret_cast<void**>(original)};
}

// ── Точка входа для кода на C++ ──────────────────────────────────────────────
// Своего потока у библиотеки нет и не будет: строковый аллокатор движка без блокировок,
// кадр вызова у скриптового потока свой, и всё, что мы делаем, законно только там.
// Поэтому C++ просыпается там же, где живёт скрипт, — на тике мода:
//
//   GRAFT_ON_TICK(dt) { ... обычный C++, можно звать движок ... }
//
// со стороны мода это одна строка в OnUpdate (её печатает `graft protogen`):
//   modded class MissionServer { void OnUpdate(float t) { super.OnUpdate(t); GraftTick(t); } }
//
// Обработчиков может быть сколько угодно; зовутся в порядке регистрации.
void on_tick(void (*fn)(float));

// ── Точка входа плагина ──────────────────────────────────────────────────────
// Единственное место, где врезка безопасна (см. выше): хост уже представился, а движок ещё
// не создал потоков и не начал компилировать скрипты. Статическая инициализация плагина
// раньше — хоста там ещё нет и `graft::hook` откажет. Поэтому код, которому нужны
// врезки (учёт аллокаций компилятора, подмена функции с первого вызова), заводят так:
//
//   GRAFT_ON_LOAD() { graft::hook(&Engine_Foo, &my_foo, &g_foo); }
//
// Зовётся один раз на плагин, в порядке регистрации; подписка позже входа в плагин уже не
// сработает. Не встали — хост об этом не узнает, поэтому причину пишут в `graft::log` сами.
void on_load(void (*fn)());


#include <exception>
#include <type_traits>

#include "graft/convert.hpp"

// Падение и исключение внутри натива: их забирает библиотека, а не движок.
//
// ЧТО ЭТО МЕНЯЕТ. Раньше кривой плагин уносил сервер целиком, и в журнале оставалось
// только «последним регистрировался такой-то». Теперь вызов, который упал, возвращает
// нулевое значение, пишет в журнал кто и где именно, а игра продолжает работать.
//
// ПОЧЕМУ ЭТО ВООБЩЕ ВОЗМОЖНО. В проекте было записано обратное — «движок ставит свой
// фильтр и валит процесс раньше нашего __except». Разбор показал другое (re/README.md):
//
//     AddVectoredExceptionHandler(0, Handler)   // 0 — в КОНЕЦ списка
//     Handler: порча кучи -> верхний фильтр; ВСЁ ОСТАЛЬНОЕ -> CONTINUE_SEARCH
//
// То есть на первом проходе движок не делает ничего, а его верхний фильтр зовётся только
// когда кадрового обработчика не нашлось. Наш — находится.
//
// ПОЧЕМУ РАНЬШЕ НЕ РАБОТАЛО. Не из-за движка, а из-за диапазона: таблица областей x64-SEH
// описывает ДИАПАЗОНЫ АДРЕСОВ, и сбой, написанный прямо в защищённой функции, оказывался
// вне её. Отсюда устройство ниже: тело вызова всегда в ОТДЕЛЬНОЙ функции, а `__try`
// охватывает вызов к ней.
//
// ЦЕНА — НОЛЬ. На x64 SEH табличный: записи раскрутки лежат в .pdata и читаются только
// когда исключение уже случилось. Замерено кейсом Perf_HotPathBudget уже со защитой на
// ВСЕХ трамплинах: bridge 1.15 против 1.21 у той же сборки без неё, guarded 0.97.
// Разницы нет — она внутри шума.
//
// ЧЕГО ЭТО НЕ ЛОВИТ, И ТЕПЕРЬ ГОВОРИТ ОБ ЭТОМ ВСЛУХ. Порчу кучи (0xC0000374) фильтр
// отдаёт дальше по цепочке сам, а не полагается на то, что движок заберёт её раньше.
// Продолжать после неё нельзя ничем: структуры аллокатора уже испорчены, следующий
// new или free упадёт в другом месте, и виноватого там не найти. Раньше фильтр обещал
// забрать её себе и держался только на том, что до него она не доходит.
//
// ПЕРЕПОЛНЕНИЕ СТЕКА (0xC00000FD) ловится, но по особому пути. Фильтр работает на ТОМ ЖЕ
// стеке, который только что кончился, поэтому там нельзя ни форматировать строку, ни
// писать в журнал — это доломает остаток. Фильтр только запоминает адрес, а отчёт пишет
// after_fault, уже на раскрученном стеке. Там же зовётся _resetstkoflw: без него
// страница-сторож не восстанавливается, и ВТОРОЕ переполнение убьёт процесс, сколько бы
// __except вокруг ни стояло.
//
// ВНИМАНИЕ ТОМУ, КТО СОБЕРЁТСЯ ДОБАВИТЬ СЮДА ВЕКТОРНЫЙ ОБРАБОТЧИК. В этом процессе
// обращение к недоступной памяти — событие ШТАТНОЕ. Так работает врезка: safetyhook
// снимает со страницы права, пишет переход и своим векторным обработчиком ловит тех, кто
// по этой странице исполняется, отвечая им «продолжай». Права снимаются со ВСЕЙ страницы,
// поэтому под раздачу попадает и соседний код.
//
// Отсюда два правила. Первое: обработчик обязан выходить на первой строке по коду
// исключения — он встанет выше кадрового и увидит КАЖДОЕ исключение процесса, а их у
// движка много. Второе: повторяющийся сбой по одному адресу здесь НЕ признак
// зацикливания, а нормальная работа окна патча. Проверено дорого — обработчик, считавший
// такие повторы аномалией, вешал сьюту наглухо.
//
// Кадрового обработчика (__try ниже) это не касается: сбой окна патча до него не доходит,
// чужой векторный отвечает раньше и цепочку прерывает. Сторожит кейс
// Hook.FaultStillReachesSehWhileHooked.
//
// А вот СНАРУЖИ окна тот же обработчик однажды отвечал «продолжай» и настоящему сбою —
// список отравленных страниц у safetyhook не чистится. Это исправлено заплаткой на
// зависимость (SRC/patches), иначе обещание выше держалось бы только на везении.
namespace graft::detail {

// Сообщить о падении. impl — адрес самого трамплина: по нему хост находит в реестре, чей
// это натив и как он называется в скрипте. what — текст исключения C++ либо nullptr,
// если это аппаратный сбой.
void note_fault(void* impl, unsigned code, const void* at, const char* what);

// Фильтр исключения: разбирает EXCEPTION_POINTERS, пишет отчёт и говорит «обрабатываем».
// Живёт в guard.cpp, потому что разбор требует windows.h, а тащить его в заголовок,
// который включает каждый плагин, — плохая сделка ради одной структуры.
//
// Работает ДО раскрутки: стек ещё цел, поэтому именно здесь снимается адрес сбоя.
long fault_filter(void* impl, unsigned long code, void* info);

// Прибраться после пойманного сбоя. Зовётся уже ИЗ ОБРАБОТЧИКА, то есть на раскрученном
// стеке, — это важно для переполнения стека, см. ниже.
//
// Делает две вещи. Возвращает глубину вложенности вызовов на уровень входа: деструкторы
// при раскрутке SEH не бегут, call_scope сам не закроется. И, если сбой был переполнением
// стека, восстанавливает страницу-сторож (_resetstkoflw) и только теперь пишет отчёт —
// в фильтре писать его было нечем, там стека уже не оставалось.
void after_fault(void* impl, std::size_t depth_was);

// ── Внутренний слой: исключения C++ ──────────────────────────────────────────
// Отдельной функцией, потому что `try` и `__try` в одной функции стоять не могут.
template <class R, class Body>
ret_abi<R> catch_cpp(void* impl, std::size_t depth_was, Body body) {
    try {
        return body();
    } catch (const std::exception& oops) {
        note_fault(impl, 0, nullptr, oops.what());
    } catch (...) {
        note_fault(impl, 0, nullptr, "exception of unknown type");
    }
    // Здесь деструкторы как раз отработали (раскрутка C++ их зовёт), но уровень всё равно
    // выставляем явно: так путь исключения и путь аппаратного сбоя чинят одно и то же.
    restore_call_depth(depth_was);
    if constexpr (!std::is_void_v<ret_abi<R>>) {
        return ret_abi<R>{};
    }
}

// ── Внешний слой: аппаратные сбои ───────────────────────────────────────────
// В этой функции не должно быть ни одного объекта с нетривиальным деструктором —
// требование компилятора к `__try`. Поэтому вся работа в теле, которое передаётся
// лямбдой: её захваты — только ABI-типы (числа и указатели).
template <class R, class Body>
ret_abi<R> guarded(void* impl, Body body) {
    // Считывается ДО __try: в защищённой функции не должно быть ничего с нетривиальным
    // деструктором, а число — можно. Стоит одно чтение thread_local.
    const std::size_t depth_was = call_depth();
    __try {
        return catch_cpp<R>(impl, depth_was, body);
    } __except (fault_filter(impl, _exception_code(), _exception_info())) {
        // Фильтр разбирает сбой, пока стек ещё цел, и решает, наш ли он вообще. Уборка —
        // здесь: стек уже раскручен, и только теперь можно чинить страницу-сторож.
        after_fault(impl, depth_was);
        if constexpr (!std::is_void_v<ret_abi<R>>) {
            return ret_abi<R>{};
        }
    }
}

}  // namespace graft::detail

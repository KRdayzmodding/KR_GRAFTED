#pragma once
#include <cstdint>

// ЖИЗНЬ ДВИЖКА, выраженная явно: этапы, слои и подписки на них.
//
// ЗАЧЕМ. Движок не сообщает о своей готовности ничем: он просто в какой-то момент
// начинает отвечать на то, на что раньше не отвечал. Пока это не было записано, каждая
// часть библиотеки заводила своё «а вдруг ещё рано»: очередь с повтором у отложенных
// нативов, флаг с предикатом у шапки, «промах не кэшируем» у поиска метода, залипающая
// самопроверка у script API (она из-за этого врала в каждом журнале). Шесть мест, шесть
// разных правил, и каждое новое просилось седьмым.
//
// КАК. Лестница этапов: монотонная (назад не ходит), с дешёвой проверкой на каждой
// ступени, с записью перехода в журнал. Двигают её только те места, где движок и так
// идёт мимо нас, — врезки. Всё остальное не спрашивает «уже можно?», а ПОДПИСЫВАЕТСЯ.
//
// Этапы и события — разное, и в типах это видно:
//   этап    случается один раз и навсегда     on(step::linked, ...)
//   событие случается сколько угодно раз      on_layer_begin(...), тик, падение натива
namespace graft::stage {

// Ступени. Порядок — это и есть лестница: каждая следующая включает предыдущую.
enum class step : std::uint8_t {
    none,     // ничего ещё не было
    armed,    // хуки стоят, плагины загружены — но движок ещё молчит
    linked,   // движок зовётся: классы находятся, шаблоны переменных и глобали есть
    running,  // пошли кадры, у объектного графа есть корень
};

// Достигнут ли этап. Дешёво: сравнение, а не поиск.
bool reached(step at);
// Где лестница сейчас.
step current();

// Позвать один раз, когда этап достигнут. Опоздавшего (подписался, когда этап уже
// пройден) зовут сразу — иначе подписка зависела бы от порядка инициализации, а он между
// единицами трансляции не определён.
void on(step at, void (*fn)());

// ── Слои ─────────────────────────────────────────────────────────────────────
// Слой — это скриптовый модуль движка (1_Core, 2_GameLib, 3_Game, 4_World, 5_Mission).
// Регистрация нативов идёт слоями, и границы видны: у каждого модуля свой script-контекст,
// и смена контекста означает, что предыдущий слой дорегистрировался.
//
// Именно на границе слоя становится доступно то, чего в предыдущем не было: игровые
// классы появляются не в 1_Core, а позже. Поэтому «попробовать ещё раз» правильно делать
// здесь, а не на каждой регистрации подряд.
struct layer {
    int index = 0;                       // порядковый номер, с единицы
    const char* first_class = nullptr;   // с чьей регистрации слой начался
    const char* last_class = nullptr;    // на чьей закончился
};

void on_layer_begin(void (*fn)(const layer&));
void on_layer_end(void (*fn)(const layer&));

// ── Двигатели: зовутся ТОЛЬКО из врезок ──────────────────────────────────────
// Врезка не знает ни про шапку, ни про отложенные нативы — она сообщает факт, а кто на
// него подписан, решают сами подписчики.

// Движок зарегистрировал метод класса. Отсюда видны границы слоёв.
void note_registration(void* context, const char* class_name);
// Движок отдал кадр: дальше есть корень объектного графа.
void note_frame();
// Проверить предикаты и сдвинуть лестницу, если пора. Зовётся из тех же врезок.
void pump();

namespace detail {
// Сдвинуть лестницу руками. Нужно двум: врезке (этапы armed/running видны ей напрямую) и
// тестам, которым живого движка взять негде.
void reach(step at);
}  // namespace detail

}  // namespace graft::stage
